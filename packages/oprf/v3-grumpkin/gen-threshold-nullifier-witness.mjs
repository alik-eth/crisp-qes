// Generate the 13-word THRESHOLD oprf_nullifier Prover.toml (2-of-3 register
// proof). Reuses the EXACT derivation of grumpkin_voprf/src/lib.nr's threshold
// test vector (Task 1), so `nargo execute` reproduces THR_NULLIFIER:
//   0x15f45ee3ae19caac1503058be2fd8108e26b93b2a943efd45ed9dfd0b7fbfc58
//
// Flow (mirrors the deployed two-proof threshold path):
//   enroll proof: M = r*H2C(id), publishes C_r = commitR(r)
//   t nodes:      each returns B_i = k_i*M + a per-share epoch-bound DLEQ
//   register:     verify the t DLEQs, idx->Kpub bind, Lagrange-combine Y in-
//                 circuit, unblind N = rinv*Y bound to r via C_r, nullifier=pedersen(N)
//
// Responder set via env RESPONDERS = "12" (default) | "13" | "23". The nullifier
// MUST be identical across responder sets (determinism / subset invariance).

import { writeFileSync } from "node:fs";
import { Fn, N, G, hashToCurve, scalarLimbs, commitR, dleqProveShare } from "./lib.mjs";

const RESP = process.env.RESPONDERS || "12";
if (!["12", "13", "23"].includes(RESP)) throw new Error(`RESPONDERS must be 12|13|23, got ${RESP}`);
const idx1 = BigInt(RESP[0]);
const idx2 = BigInt(RESP[1]);

const det = (l) => (BigInt("0x" + Buffer.from(l).toString("hex")) % (N - 1n)) + 1n;

// Same identity material + blind as the single-key tests (so M / r / C_r match).
const r = det("crisp-qes-test-r");
const M = hashToCurve(new TextEncoder().encode("1234567890")).multiply(r);
const rinv = Fn.inv(Fn.create(r));
const cR = await commitR(r);

// Fresh threshold key k' via degree-1 poly f(x) = k' + a*x; shares f(1),f(2),f(3).
const kPrime = det("crisp-qes-threshold-kprime-epoch1");
const a = det("crisp-qes-threshold-poly-a1");
const f = (x) => Fn.add(Fn.create(kPrime), Fn.mul(Fn.create(a), Fn.create(x)));
const k = { 1: f(1n), 2: f(2n), 3: f(3n) };

const Kpub = {}, B = {};
for (const i of [1, 2, 3]) {
    Kpub[i] = G.multiply(Fn.create(k[i]));
    B[i] = M.multiply(Fn.create(k[i]));
}

// Session epoch (bound into every per-share DLEQ transcript).
const epoch = det("crisp-qes-threshold-epoch-1");

// Per-share DLEQs with the SAME deterministic nonces as the Task 1 vector, so
// the produced (c,z) reproduce the pinned constants exactly.
const D = {};
for (const i of [1, 2, 3]) {
    D[i] = await dleqProveShare(Kpub[i], k[i], M, B[i], epoch, det("crisp-qes-thr-nonce-" + i));
}

const aff = (P) => P.toAffine();
const dec = (v) => v.toString();
const pa = (P) => { const o = aff(P); return { x: o.x, y: o.y }; };

// Responder a = idx1, b = idx2 (the witness passes their B + DLEQ by index).
const a_i = Number(idx1), b_i = Number(idx2);
const Ba = pa(B[a_i]), Bb = pa(B[b_i]);
const Da = D[a_i], Db = D[b_i];
const DaL = { c: scalarLimbs(Da.c), z: scalarLimbs(Da.z) };
const DbL = { c: scalarLimbs(Db.c), z: scalarLimbs(Db.z) };

const Maff = aff(M);
const K1 = pa(Kpub[1]), K2 = pa(Kpub[2]), K3 = pa(Kpub[3]);
const rL = scalarLimbs(r), riL = scalarLimbs(rinv);

const toml = `# auto-generated by gen-threshold-nullifier-witness.mjs (2-of-3 register ABI)
# 13-word public layout: mx[0] my[1] kp1x[2] kp1y[3] kp2x[4] kp2y[5] kp3x[6]
#   kp3y[7] idx1[8] idx2[9] epoch[10] c_r[11], return nullifier[12].
# Responders {${RESP[0]},${RESP[1]}}; Y is combined IN-CIRCUIT (no free Y input).
mx = "${dec(Maff.x)}"
my = "${dec(Maff.y)}"
kp1x = "${dec(K1.x)}"
kp1y = "${dec(K1.y)}"
kp2x = "${dec(K2.x)}"
kp2y = "${dec(K2.y)}"
kp3x = "${dec(K3.x)}"
kp3y = "${dec(K3.y)}"
idx1 = "${dec(idx1)}"
idx2 = "${dec(idx2)}"
epoch = "${dec(epoch)}"
c_r = "${cR}"
bax = "${dec(Ba.x)}"
bay = "${dec(Ba.y)}"
bbx = "${dec(Bb.x)}"
bby = "${dec(Bb.y)}"
ca_lo = "${dec(DaL.c.lo)}"
ca_hi = "${dec(DaL.c.hi)}"
za_lo = "${dec(DaL.z.lo)}"
za_hi = "${dec(DaL.z.hi)}"
cb_lo = "${dec(DbL.c.lo)}"
cb_hi = "${dec(DbL.c.hi)}"
zb_lo = "${dec(DbL.z.lo)}"
zb_hi = "${dec(DbL.z.hi)}"
r_lo = "${dec(rL.lo)}"
r_hi = "${dec(rL.hi)}"
rinv_lo = "${dec(riL.lo)}"
rinv_hi = "${dec(riL.hi)}"
`;

writeFileSync(new URL("./circuits/oprf_nullifier/Prover.toml", import.meta.url), toml);
console.log(`wrote threshold Prover.toml (responders {${RESP[0]},${RESP[1]}})`);
console.log("c_r   =", "0x" + cR.toString(16).padStart(64, "0"));
console.log("epoch =", epoch.toString());
