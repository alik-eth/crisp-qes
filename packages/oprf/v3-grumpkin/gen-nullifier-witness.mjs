// Generate Prover.toml for the oprf_nullifier circuit from the JS lib.
// Flow (mirrors the live protocol):
//   client: M = r*H2C(input)            (blinded element, r = blinding scalar)
//   node:   Y = k*M, DLEQ proof (c, z)  (Kpub = k*G is the node public key)
//   client: verify DLEQ, N = rinv*Y, nullifier = pedersen(N)
// If `nargo execute` succeeds and bb verifies, the Noir DLEQ-verify + unblind +
// commitment matches the JS lib bit-for-bit (incl. the Fiat-Shamir pedersen).

import { writeFileSync } from "node:fs";
import { Fp, Fn, N, G, hashToCurve, scalarLimbs, oprfEval, dleqProve } from "./lib.mjs";

const RNOKPP = new TextEncoder().encode("1234567890");

// Deterministic test scalars in [1, N).
const det = (label) => (BigInt("0x" + Buffer.from(label).toString("hex")) % (N - 1n)) + 1n;
const r = det("crisp-qes-test-r");          // client blinding scalar
const k = det("crisp-qes-node-secret-k");   // node OPRF secret
const t = det("crisp-qes-dleq-nonce-t");    // DLEQ proof nonce

const Kpub = G.multiply(k);                  // node public key
const Hpt = hashToCurve(RNOKPP);             // H2C(input)
const M = Hpt.multiply(r);                   // blinded element
const Y = oprfEval(k, M);                    // node response Y = k*M
const { c, z } = await dleqProve(k, Kpub, M, Y, t);

// Unblind: N = rinv*Y. rinv is the multiplicative inverse of r mod N.
const rinv = Fn.inv(Fn.create(r));
const Npt = Y.multiply(rinv);                // = (rinv*k*r)*H = k*H (the OPRF output point)

const aff = (P) => P.toAffine();
const Ga = aff(G), Ka = aff(Kpub), Ma = aff(M), Ya = aff(Y);

const cL = scalarLimbs(c);
const zL = scalarLimbs(z);
const riL = scalarLimbs(rinv);
const rL = scalarLimbs(r);

const toml = `# auto-generated by gen-nullifier-witness.mjs (v3 Grumpkin OPRF)
gx = "${Ga.x}"
gy = "${Ga.y}"
kpx = "${Ka.x}"
kpy = "${Ka.y}"
mx = "${Ma.x}"
my = "${Ma.y}"
yx = "${Ya.x}"
yy = "${Ya.y}"
c_lo = "${cL.lo}"
c_hi = "${cL.hi}"
z_lo = "${zL.lo}"
z_hi = "${zL.hi}"
rinv_lo = "${riL.lo}"
rinv_hi = "${riL.hi}"
r_lo = "${rL.lo}"
r_hi = "${rL.hi}"
c_expected = "${c}"
`;

writeFileSync(new URL("./circuits/oprf_nullifier/Prover.toml", import.meta.url), toml);
console.log("wrote Prover.toml");
console.log("c (challenge) =", c.toString());
console.log("z (response)  =", z.toString());
const Naff = aff(Npt);
console.log("N (unblinded) =", Naff.x.toString(), Naff.y.toString());
