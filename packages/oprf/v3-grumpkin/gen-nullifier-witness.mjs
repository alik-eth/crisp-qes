// Generate Prover.toml for the oprf_nullifier circuit (the /v3/register proof).
// Flow (mirrors the live two-proof protocol):
//   enroll proof: M = r*H2C(input), publishes C_r = commitR(r)   (gates blind-eval)
//   node:         Y = k*M, DLEQ proof (c, z)  (Kpub = k*G the node public key)
//   register:     verify DLEQ, N = rinv*Y, bind rinv to enroll's r via C_r,
//                 nullifier = pedersen(N)
// New 8-word ABI (F1+F2 closed): the free DLEQ base G.x/G.y and the redundant
// c_expected are GONE (GEN is the lib's pinned global; C-1 is the lib's limb
// binding). Public inputs: kpx,kpy, yx,yy, mx,my, c_r. Private: r,rinv,c,z limbs.
// If `nargo execute` solves and returns the recovery-anchor nullifier, the Noir
// register proof matches the JS lib bit-for-bit.

import { writeFileSync } from "node:fs";
import { Fn, N, G, hashToCurve, scalarLimbs, oprfEval, dleqProve, commitR } from "./lib.mjs";

const RNOKPP = new TextEncoder().encode("1234567890");

// Deterministic test scalars in [1, N). r and k MUST match the enroll generator.
const det = (label) => (BigInt("0x" + Buffer.from(label).toString("hex")) % (N - 1n)) + 1n;
const r = det("crisp-qes-test-r");          // client blinding scalar (== enroll's r)
const k = det("crisp-qes-node-secret-k");   // node OPRF secret
const t = det("crisp-qes-dleq-nonce-t");    // DLEQ proof nonce

const Kpub = G.multiply(k);                  // node public key Kpub = k*G
const Hpt = hashToCurve(RNOKPP);             // H2C(input)
const M = Hpt.multiply(r);                   // blinded element M = r*H2C(input)
const Y = oprfEval(k, M);                    // node response Y = k*M
const { c, z } = await dleqProve(k, Kpub, M, Y, t);

// Unblind: N = rinv*Y. rinv is the multiplicative inverse of r mod N.
const rinv = Fn.inv(Fn.create(r));
const Npt = Y.multiply(rinv);                // = (rinv*k*r)*H = k*H (OPRF output point)

// Cross-proof shared-r commitment (== enroll's C_r).
const cR = await commitR(r);

const aff = (P) => P.toAffine();
const Ka = aff(Kpub), Ma = aff(M), Ya = aff(Y);

const cL = scalarLimbs(c);
const zL = scalarLimbs(z);
const riL = scalarLimbs(rinv);
const rL = scalarLimbs(r);

const toml = `# auto-generated by gen-nullifier-witness.mjs (v3 two-proof register proof)
# 8-word public layout: kpx[0] kpy[1] yx[2] yy[3] mx[4] my[5] c_r[6], return nullifier[7].
# F1 closed: no free G.x/G.y. C-1 is the lib's limb binding: no c_expected.
kpx = "${Ka.x}"
kpy = "${Ka.y}"
yx = "${Ya.x}"
yy = "${Ya.y}"
mx = "${Ma.x}"
my = "${Ma.y}"
c_r = "${cR}"
r_lo = "${rL.lo}"
r_hi = "${rL.hi}"
rinv_lo = "${riL.lo}"
rinv_hi = "${riL.hi}"
c_lo = "${cL.lo}"
c_hi = "${cL.hi}"
z_lo = "${zL.lo}"
z_hi = "${zL.hi}"
`;

writeFileSync(new URL("./circuits/oprf_nullifier/Prover.toml", import.meta.url), toml);
console.log("wrote Prover.toml");
console.log("c_r (commitR) =", "0x" + cR.toString(16).padStart(64, "0"));
const Naff = aff(Npt);
console.log("N (unblinded) =", Naff.x.toString(), Naff.y.toString());
