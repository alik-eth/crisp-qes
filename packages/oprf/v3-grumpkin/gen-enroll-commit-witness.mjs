// Generate Prover.toml for the FUSED enroll_commit circuit.
//
// Combines the qes_frontend witness (synthetic P-256 cert + ECDSA over
// sha256(signedAttrs) + DER RNOKPP/DOB offsets) with the hash-to-curve
// witness (u0,u1 = hashToField2(RNOKPP), SvdW hints, blinding scalar r,
// M = r*H2C(RNOKPP)). Also computes the in-circuit Pedersen binding
// rnokpp_commit = pedersen_hash([rnokpp_field]) so we can cross-check the
// circuit's public output.
//
// SYNTHETIC disposable cert only. NEVER reads fixtures/diia. Run with cwd in
// v3-grumpkin (module resolution).

import { writeFileSync } from "node:fs";
import { p256 } from "../node_modules/@noble/curves/p256.js";
import { sha256 } from "../node_modules/@noble/hashes/sha2.js";
import {
  Fp,
  N,
  SVDW_CONSTS,
  mapToCurveSvdW,
  hashToField2,
  scalarLimbs,
} from "./lib.mjs";

const CERT_LEN = 768;

// --- synthetic identity ---
const RNOKPP = "1234567890"; // 10 ASCII digits
const DOB = "19900115"; // YYYYMMDD, clearly > 18 yrs ago
const TODAY = "20260530"; // public current date YYYYMMDD

// --- build a synthetic DER-ish buffer (identical layout to gen-qes-witness) ---
const cert = new Uint8Array(CERT_LEN);
for (let i = 0; i < CERT_LEN; i++) cert[i] = (i * 31 + 7) & 0xff; // deterministic filler

const rnokppOff = 64;
const oid = [0x06, 0x03, 0x55, 0x04, 0x05, 0x13, 0x0a];
for (let i = 0; i < oid.length; i++) cert[rnokppOff + i] = oid[i];
for (let i = 0; i < 10; i++) cert[rnokppOff + 7 + i] = RNOKPP.charCodeAt(i);

const dobOff = 200;
for (let i = 0; i < 8; i++) cert[dobOff + i] = DOB.charCodeAt(i);

// --- signedAttrs = the whole synthetic cert buffer (stand-in); hash it ---
const msghash = sha256(cert);

// --- fresh disposable P-256 keypair, sign the hash (no re-prehash) ---
const sk = p256.utils.randomPrivateKey();
const pubUncompressed = p256.getPublicKey(sk, false); // 0x04 || X[32] || Y[32]
const pubX = pubUncompressed.slice(1, 33);
const pubY = pubUncompressed.slice(33, 65);
// noble does NOT enforce low-s; the Noir stdlib verify_signature requires it.
const sigObj = p256.sign(msghash, sk, { prehash: false }).normalizeS();
const sig = sigObj.toCompactRawBytes(); // r[32] || s[32], 64 bytes (low-s)
if (!p256.verify(sigObj, msghash, pubUncompressed, { prehash: false })) {
  throw new Error("JS-side ECDSA verify failed");
}

// --- folded RNOKPP Field (must equal the circuit's base-10 accumulate) ---
let rnokppField = 0n;
for (const c of RNOKPP) rnokppField = rnokppField * 10n + BigInt(c.charCodeAt(0) - 0x30);

// --- OPRF commitment witness: u0,u1 from the SAME RNOKPP, SvdW hints, M ---
const rnokppBytes = new TextEncoder().encode(RNOKPP);
const [u0, u1] = hashToField2(rnokppBytes);
const m0 = mapToCurveSvdW(u0);
const m1 = mapToCurveSvdW(u1);
const Hpt = m0.point.add(m1.point); // H2C(RNOKPP)

// r: deterministic test scalar in [1, N)
const r = (BigInt("0x" + Buffer.from("crisp-qes-test-r").toString("hex")) % (N - 1n)) + 1n;
const M = Hpt.multiply(r); // M = r*H2C(RNOKPP)
const Maff = M.toAffine();

const { c1, c2, c3, c4 } = SVDW_CONSTS;
const { lo, hi } = scalarLimbs(r);

// --- in-circuit binding: pedersen_hash([rnokpp_field]) via bb.js ---
// Mirrors lib.mjs's verified bb.js<->Noir pedersen equivalence.
const { BarretenbergSync } = await import("@aztec/bb.js");
const bb = await BarretenbergSync.initSingleton();
const toBE32 = (v) => {
  const o = new Uint8Array(32);
  for (let i = 31; i >= 0; i--) {
    o[i] = Number(v & 0xffn);
    v >>= 8n;
  }
  return o;
};
const pedRes = bb.pedersenHash({ inputs: [toBE32(Fp.create(rnokppField))], hashIndex: 0 });
let rnokppCommit = 0n;
for (const b of pedRes.hash) rnokppCommit = (rnokppCommit << 8n) | BigInt(b);

// --- emit Prover.toml ---
const arr = (u8) => "[" + Array.from(u8).map((b) => `"${b}"`).join(", ") + "]";
const hintArr = (h) => `["${h.inv_t}", "${h.e1}", "${h.w1}", "${h.e2}", "${h.w2}", "${h.sqrt_x}"]`;

const toml = `# auto-generated by gen-enroll-commit-witness.mjs (v3 Grumpkin OPRF, enroll_commit)
# SYNTHETIC disposable cert only. Never a real Diia cert.
pubkey_x = ${arr(pubX)}
pubkey_y = ${arr(pubY)}
sig = ${arr(sig)}
msghash = ${arr(msghash)}
cert = ${arr(cert)}
rnokpp_oid_off = "${rnokppOff}"
dob_off = "${dobOff}"
today = ${arr(Array.from(TODAY).map((c) => c.charCodeAt(0)))}
u0 = "${u0}"
u1 = "${u1}"
c1 = "${c1}"
c2 = "${c2}"
c3 = "${c3}"
c4 = "${c4}"
h0 = ${hintArr(m0.hints)}
h1 = ${hintArr(m1.hints)}
r_lo = "${lo}"
r_hi = "${hi}"
`;

writeFileSync(new URL("./circuits/enroll_commit/Prover.toml", import.meta.url), toml);
console.log("wrote Prover.toml");
console.log("RNOKPP                 =", RNOKPP);
console.log("DOB                    =", DOB, " today =", TODAY);
console.log("rnokpp_field           =", rnokppField.toString());
console.log("expected public outputs (return tuple):");
console.log("  M.x           =", Maff.x.toString());
console.log("  M.y           =", Maff.y.toString());
console.log("  rnokpp_commit =", rnokppCommit.toString());
