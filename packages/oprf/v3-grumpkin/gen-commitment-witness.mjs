// Generate Prover.toml for the oprf_commitment circuit from the JS lib, for a
// test RNOKPP. If `nargo execute` succeeds, the Noir SvdW+scalarmul produced
// the SAME M = r*H2C(input) as the validated JS lib -> circuit is correct.

import { writeFileSync } from "node:fs";
import { Fp, N, SVDW_CONSTS, mapToCurveSvdW, hashToField2, Point, scalarLimbs } from "./lib.mjs";

const RNOKPP = new TextEncoder().encode("1234567890");

// r: deterministic test scalar in [1, N)
const r = (BigInt("0x" + Buffer.from("crisp-qes-test-r").toString("hex")) % (N - 1n)) + 1n;

const [u0, u1] = hashToField2(RNOKPP);
const m0 = mapToCurveSvdW(u0);
const m1 = mapToCurveSvdW(u1);
const Hpt = m0.point.add(m1.point);          // H2C(input)
const M = Hpt.multiply(r);                    // M = r*H2C(input)
const Maff = M.toAffine();

const { c1, c2, c3, c4 } = SVDW_CONSTS;
const { lo, hi } = scalarLimbs(r);
const hintArr = (h) => `["${h.inv_t}", "${h.e1}", "${h.w1}", "${h.e2}", "${h.w2}", "${h.sqrt_x}"]`;

const toml = `# auto-generated by gen-commitment-witness.mjs (v3 Grumpkin OPRF)
u0 = "${u0}"
u1 = "${u1}"
c1 = "${c1}"
c2 = "${c2}"
c3 = "${c3}"
c4 = "${c4}"
h0 = ${hintArr(m0.hints)}
h1 = ${hintArr(m1.hints)}
r_lo = "${lo}"
r_hi = "${hi}"
mx = "${Maff.x}"
my = "${Maff.y}"
`;

writeFileSync(new URL("./circuits/oprf_commitment/Prover.toml", import.meta.url), toml);
console.log("wrote Prover.toml");
console.log("expected M.x =", Maff.x.toString());
console.log("expected M.y =", Maff.y.toString());
